#!/usr/bin/env python3
"""Lessons: what failed, why, and the guard that stops it recurring.

docs/ops/lessons.yaml is the source of truth; LESSONS.md is rendered from it (like board.py).

  lessons.py add --surfaced WHERE --symptom TEXT [--cause TEXT] [--guard-text TEXT]
                 [--key KEY] [--source manual|merge_ready|stress] [--branch B] [--sha SHA]
                 [--failing LINE ...] [--no-render]
      New lesson (status open). If an existing lesson has the same --key, record a
      recurrence on it instead (and reopen it if it was closed: its guard did not hold).
  lessons.py list [--status open|closed] [--format text|tsv]
  lessons.py close ID --guard REF [--guard REF ...] [--no-render]
      Refuses unless every REF resolves:
        test:<path>[::<test name>]     tracked test file exists (and defines the test)
        config:<file>:<dotted.key>     key exists in a .toml/.yaml/.yml file
        rule:<file>:<text>             the text is a line in docs/ops/prompts/*.md,
                                       docs/ops/PROTOCOL.md or CLAUDE.md
  lessons.py render [--out PATH]      writes docs/ops/LESSONS.md
  lessons.py stats [--format text|tsv]
      lessons, open, closed, recurrences, lessons that recurred, mean time to guard (h)
  lessons.py validate

Single writer: the coordinator, plus merge_ready.sh / stress.sh stubs. Workers propose a
lesson in their report; they write the guard (test, config, rule) on their branch.
Exit codes: 0 ok · 1 error / refused · 2 usage.  Standard library + PyYAML only.
"""

from __future__ import annotations

import argparse
import datetime as dt
import os
import re
import sys
import tempfile
import tomllib
from pathlib import Path
from typing import Any

try:
    import yaml
except ImportError:  # pragma: no cover
    sys.stderr.write("lessons.py needs PyYAML: run it with the project venv python\n")
    sys.exit(2)

REL = "docs/ops/lessons.yaml"
REPO = Path(__file__).resolve().parents[2]
STATUSES = ("open", "closed")
REQUIRED = ("id", "created", "surfaced", "symptom", "cause", "guard", "status")
RULE_FILES = ("docs/ops/prompts/", "docs/ops/PROTOCOL.md", "CLAUDE.md")
ID_RE = re.compile(r"^L(\d+)$")

HEADER = """\
# Lessons: SOURCE OF TRUTH. Writers: the coordinator (tools/ops/lessons.py), and the
# merge_ready.sh / stress.sh stubs. docs/ops/LESSONS.md is generated by
# `tools/ops/lessons.py render`; do not edit it by hand.
# A lesson closes only when its guard exists: `lessons.py close ID --guard REF`.
"""

Data = dict[str, Any]
Lesson = dict[str, Any]


class LessonError(Exception):
    pass


def _out(*parts: object, file=None) -> None:
    (file or sys.stdout).write(" ".join(str(p) for p in parts) + "\n")


def _now() -> str:
    return dt.datetime.now(dt.UTC).strftime("%Y-%m-%dT%H:%M:%SZ")


def _parse_time(s: str) -> dt.datetime:
    """'2026-11-11' or '2026-11-11T10:00:00Z' -> aware UTC datetime."""
    s = str(s)
    if len(s) == 10:
        return dt.datetime.fromisoformat(s).replace(tzinfo=dt.UTC)
    return dt.datetime.fromisoformat(s)  # accepts a trailing "Z" (Python 3.11+)


# ---------------------------------------------------------------- load / save / validate


def validate(data: Any) -> list[str]:
    if not isinstance(data, dict) or not isinstance(data.get("lessons"), list):
        return ["lessons file must be a mapping with a `lessons` list"]
    errs: list[str] = []
    seen: set[str] = set()
    for i, le in enumerate(data["lessons"]):
        if not isinstance(le, dict):
            errs.append(f"lesson #{i}: not a mapping")
            continue
        lid = le.get("id", f"#{i}")
        for k in REQUIRED:
            if k not in le:
                errs.append(f"{lid}: missing `{k}`")
        if not ID_RE.match(str(lid)):
            errs.append(f"{lid}: id must look like L<n>")
        if lid in seen:
            errs.append(f"{lid}: duplicate id")
        seen.add(lid)
        if le.get("status") not in STATUSES:
            errs.append(f"{lid}: bad status {le.get('status')!r}")
        if le.get("status") == "closed" and not le.get("guard_refs"):
            errs.append(f"{lid}: closed without guard_refs")
    return errs


def default_file() -> Path:
    return REPO / REL


def load(file: Path | None = None) -> Data:
    path = file or default_file()
    if not path.exists():
        raise LessonError(f"no lessons file at {path}")
    data = yaml.safe_load(path.read_text(encoding="utf-8"))
    errs = validate(data)
    if errs:
        raise LessonError("invalid lessons file:\n  " + "\n  ".join(errs))
    return data


def save(data: Data, file: Path | None = None) -> Path:
    errs = validate(data)
    if errs:
        raise LessonError("refusing to save invalid lessons:\n  " + "\n  ".join(errs))
    path = file or default_file()
    body = yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=200)
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=".lessons.", suffix=".yaml")
    with os.fdopen(fd, "w", encoding="utf-8") as fh:
        fh.write(HEADER + body)
    os.replace(tmp, path)
    return path


def repo_of(file: Path) -> Path:
    """The repo a lessons file belongs to: <repo>/docs/ops/lessons.yaml."""
    return file.resolve().parents[2]


# ---------------------------------------------------------------- operations


def next_id(data: Data) -> str:
    nums = [int(m.group(1)) for le in data["lessons"] if (m := ID_RE.match(str(le["id"])))]
    return f"L{max(nums, default=0) + 1}"


def find(data: Data, lid: str) -> Lesson:
    for le in data["lessons"]:
        if le["id"] == lid:
            return le
    raise LessonError(f"no lesson {lid}")


def add(data: Data, *, surfaced: str, symptom: str, cause: str = "", guard_text: str = "",
        key: str | None = None, source: str = "manual", branch: str | None = None,
        sha: str | None = None, failing: list[str] | None = None,
        now: str | None = None) -> tuple[Lesson, bool]:
    """Returns (lesson, created). An existing lesson with the same key gets a recurrence."""
    now = now or _now()
    event = {k: v for k, v in (("at", now), ("source", source), ("branch", branch),
                                ("sha", sha), ("failing", failing or None)) if v}
    if key:
        for le in data["lessons"]:
            if le.get("key") == key:
                le.setdefault("recurrences", []).append(event)
                if le["status"] == "closed":  # the guard did not hold
                    le["status"] = "open"
                    le["reopened"] = now
                return le, False
    le: Lesson = {
        "id": next_id(data),
        "created": now,
        "surfaced": surfaced,
        "symptom": symptom,
        "cause": cause or "TODO: root cause",
        "guard": guard_text or "TODO: guard (test, config key or prompt rule)",
        "status": "open",
    }
    if key:
        le["key"] = key
    if source != "manual" or branch or sha or failing:
        le["origin"] = event
    data["lessons"].append(le)
    return le, True


def check_ref(ref: str, repo: Path) -> str | None:
    """None when the guard reference resolves, else the reason it does not."""
    kind, _, rest = ref.partition(":")
    if kind == "test":
        path, _, name = rest.partition("::")
        p = repo / path
        if not path.startswith("tests/") or not p.is_file():
            return f"test file {path!r} not found under tests/"
        if name and not re.search(rf"^\s*(async\s+)?def {re.escape(name)}\(", p.read_text(
                encoding="utf-8"), re.MULTILINE):
            return f"{path} defines no test {name!r}"
        return None
    if kind == "config":
        path, _, dotted = rest.rpartition(":")
        p = repo / path
        if not path or not p.is_file():
            return f"config file {path!r} not found"
        try:
            if p.suffix == ".toml":
                node: Any = tomllib.loads(p.read_text(encoding="utf-8"))
            elif p.suffix in (".yaml", ".yml"):
                node = yaml.safe_load(p.read_text(encoding="utf-8"))
            else:
                return f"{path}: config refs must point at .toml or .yaml"
        except Exception as e:  # noqa: BLE001 - report any parse error as a refusal
            return f"{path}: cannot parse ({type(e).__name__})"
        for part in dotted.split("."):
            if not isinstance(node, dict) or part not in node:
                return f"{path} has no key {dotted!r}"
            node = node[part]
        return None
    if kind == "rule":
        path, _, text = rest.partition(":")
        if not any(path == f or (f.endswith("/") and path.startswith(f)) for f in RULE_FILES):
            return f"rule refs must point at {', '.join(RULE_FILES)}"
        p = repo / path
        if not p.is_file():
            return f"rule file {path!r} not found"
        if not text.strip() or text.strip() not in p.read_text(encoding="utf-8"):
            return f"{path} does not contain the rule text {text.strip()!r}"
        return None
    return f"unknown guard kind {kind!r} (use test:, config: or rule:)"


def close(data: Data, lid: str, refs: list[str], repo: Path, now: str | None = None) -> Lesson:
    if not refs:
        raise LessonError("close needs at least one --guard REF")
    le = find(data, lid)
    problems = [f"{r}: {why}" for r in refs if (why := check_ref(r, repo))]
    if problems:
        raise LessonError(f"refusing to close {lid}; guard not found:\n  " + "\n  ".join(problems))
    le["status"] = "closed"
    le["guard_refs"] = list(refs)
    le["closed"] = now or _now()
    return le


def stats(data: Data) -> dict[str, Any]:
    ls = data["lessons"]
    closed = [le for le in ls if le["status"] == "closed" and le.get("closed")]
    hours = [(_parse_time(le["closed"]) - _parse_time(le["created"])).total_seconds() / 3600
             for le in closed]
    return {
        "lessons": len(ls),
        "open": sum(le["status"] == "open" for le in ls),
        "closed": len(closed),
        "recurrences": sum(len(le.get("recurrences") or []) for le in ls),
        "recurred": sum(bool(le.get("recurrences")) for le in ls),
        "mean_hours_to_guard": round(sum(hours) / len(hours), 1) if hours else None,
    }


# ---------------------------------------------------------------- render


def _cell(x: Any) -> str:
    return str(x if x is not None else "").replace("|", "\\|").replace("\n", " ")


def render(data: Data) -> str:
    s = stats(data)
    out = [
        "# Lessons: what failed, why, and the guard that stops it recurring",
        "",
        ("<!-- GENERATED by `tools/ops/lessons.py render` from docs/ops/lessons.yaml. "
         "Do not edit. -->"),
        "",
        "The loop learns from failure. Every RED merge, revert, flaky test, review rejection or",
        "coordination mistake gets one entry. An entry closes only when its **guard** exists",
        "(`lessons.py close ID --guard test:…|config:…|rule:…` checks it). Every worker reads",
        "this file before starting each task (docs/ops/prompts/*.md).",
        "",
        (f"{s['lessons']} lessons · {s['open']} open · {s['closed']} closed · "
         f"{s['recurrences']} recurrences · mean time to guard: "
         f"{s['mean_hours_to_guard'] if s['mean_hours_to_guard'] is not None else '–'} h"),
    ]
    for status in ("open", "closed"):
        rows = [le for le in data["lessons"] if le["status"] == status]
        out += ["", f"## {status} ({len(rows)})", "",
                "| ID | Date | Surfaced in | Symptom | Root cause | Guard | Recurred |",
                "|---|---|---|---|---|---|---|"]
        for le in rows:
            guard = le["guard"]
            if le.get("guard_refs"):
                guard += " — " + ", ".join(f"`{r}`" for r in le["guard_refs"])
            out.append("| " + " | ".join(_cell(x) for x in (
                le["id"], str(le["created"])[:10], le["surfaced"], le["symptom"], le["cause"],
                guard, len(le.get("recurrences") or []) or "")) + " |")
    return "\n".join(out) + "\n"


def _render_next_to(file: Path) -> Path:
    out = file.with_name("LESSONS.md")
    out.write_text(render(load(file)), encoding="utf-8")
    return out


# ---------------------------------------------------------------- CLI


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(prog="lessons.py", description=__doc__.split("\n")[0])
    p.add_argument("--file", help="lessons yaml (default: <repo>/docs/ops/lessons.yaml)")
    sub = p.add_subparsers(dest="cmd", required=True)

    pa = sub.add_parser("add")
    pa.add_argument("--surfaced", required=True)
    pa.add_argument("--symptom", required=True)
    pa.add_argument("--cause", default="")
    pa.add_argument("--guard-text", default="")
    pa.add_argument("--key")
    pa.add_argument("--source", default="manual", choices=("manual", "merge_ready", "stress"))
    pa.add_argument("--branch")
    pa.add_argument("--sha")
    pa.add_argument("--failing", nargs="*", default=[])
    pa.add_argument("--no-render", action="store_true")

    pl = sub.add_parser("list")
    pl.add_argument("--status", choices=STATUSES)
    pl.add_argument("--format", choices=("text", "tsv"), default="text")

    pc = sub.add_parser("close")
    pc.add_argument("id")
    pc.add_argument("--guard", action="append", default=[], metavar="REF")
    pc.add_argument("--no-render", action="store_true")

    pr = sub.add_parser("render")
    pr.add_argument("--out")
    ps = sub.add_parser("stats")
    ps.add_argument("--format", choices=("text", "tsv"), default="text")
    sub.add_parser("validate")
    args = p.parse_args(argv)

    file = Path(args.file) if args.file else default_file()
    try:
        data = load(file)
        if args.cmd == "add":
            le, created = add(data, surfaced=args.surfaced, symptom=args.symptom,
                              cause=args.cause, guard_text=args.guard_text, key=args.key,
                              source=args.source, branch=args.branch, sha=args.sha,
                              failing=args.failing)
            save(data, file)
            if not args.no_render:
                _render_next_to(file)
            n = len(le.get("recurrences") or [])
            _out(f"added {le['id']}" if created
                 else (f"recurrence #{n} of {le['id']} (status {le['status']})"))
            return 0
        if args.cmd == "close":
            le = close(data, args.id, args.guard, repo_of(file))
            save(data, file)
            if not args.no_render:
                _render_next_to(file)
            _out(f"closed {le['id']}: " + ", ".join(le["guard_refs"]))
            return 0
        if args.cmd == "list":
            for le in data["lessons"]:
                if args.status and le["status"] != args.status:
                    continue
                cols = (le["id"], le["status"], str(le["created"])[:10], le["surfaced"],
                        le["symptom"], len(le.get("recurrences") or []))
                recurred = f"  (recurred {cols[5]}x)" if cols[5] else ""
                text = f"{cols[0]:<4} {cols[1]:<6} {cols[2]}  {cols[3]}: {cols[4]}{recurred}"
                _out("\t".join(map(str, cols)) if args.format == "tsv" else text)
            return 0
        if args.cmd == "render":
            out = Path(args.out) if args.out else file.with_name("LESSONS.md")
            out.write_text(render(data), encoding="utf-8")
            _out(f"wrote {out.name}")
            return 0
        if args.cmd == "stats":
            s = stats(data)
            if args.format == "tsv":
                _out("\t".join(f"{k}={v}" for k, v in s.items()))
            else:
                _out(" ".join(f"{k}={v}" for k, v in s.items()))
            return 0
        if args.cmd == "validate":
            _out(f"ok: {len(data['lessons'])} lessons")
            return 0
    except LessonError as e:
        _out(f"error: {e}", file=sys.stderr)
        return 1
    return 2


if __name__ == "__main__":
    sys.exit(main())
