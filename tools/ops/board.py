#!/usr/bin/env python3
"""Team task board. docs/ops/board.yaml is the source of truth; BOARD.md is rendered from it.

  board.py list [--owner X] [--state S] [--next [--exclude ID ...]] [--format text|tsv]
  board.py move ID STATE [--sha SHA]          (coordinator; edits the working-tree file)
  board.py render [--out PATH]                (writes docs/ops/BOARD.md)
  board.py validate
  board.py owners                             (tsv: id, session, branch; one line per branch)

`list` reads the board committed on main (`git show main:docs/ops/board.yaml`) so a worker
sees the coordinator's latest view from any worktree; it falls back to the working-tree file
if main has none yet. `--file PATH` or `--ref REF` overrides the source.

Next task for an owner: its first `doing` row (resume), else its first `todo` row whose
blockers are all satisfied. A blocker is satisfied when it is `done`, or when it belongs to
the same owner and is in `review` or listed in --exclude (the work is already on that
owner's branch). A blocker that is not a task ID (e.g. "user supplies scripts") is external
and stays unsatisfied until the coordinator removes it.
Exit codes: 0 ok · 1 error / invalid board · 3 `--next` found nothing.
Standard library + PyYAML only.
"""

from __future__ import annotations

import argparse
import datetime as dt
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any

try:
    import yaml
except ImportError:  # pragma: no cover
    sys.stderr.write("board.py needs PyYAML: run it with the project venv python "
                     "(e.g. $VENV/bin/python tools/ops/board.py ...)\n")
    sys.exit(2)

STATES = ("proposed", "todo", "doing", "review", "done")
RENDER_ORDER = ("todo", "doing", "review", "done", "proposed")
REQUIRED = ("id", "title", "owner", "branch", "state", "blockers", "done_when")
ID_RE = re.compile(r"^[A-Z]+-\d+$|^SCAF$")
REL = "docs/ops/board.yaml"
REPO = Path(__file__).resolve().parents[2]

HEADER = """\
# Task board: SOURCE OF TRUTH. Single writer: the coordinator (via tools/ops/board.py).
# Workers read it with: tools/ops/board.py list --owner <id> --next
# docs/ops/BOARD.md is generated by `tools/ops/board.py render`; do not edit it by hand.
# state: proposed | todo | doing | review | done.  sha: merge (done) or branch tip (review).
"""

Board = dict[str, Any]
Task = dict[str, Any]


def _out(*parts: object, file=None) -> None:
    """CLI output (the project bans print(); see ruff T20)."""
    (file or sys.stdout).write(" ".join(str(p) for p in parts) + "\n")


class BoardError(Exception):
    pass


# ---------------------------------------------------------------- load / save / validate

def validate(data: Any) -> list[str]:
    errs: list[str] = []
    if not isinstance(data, dict) or not isinstance(data.get("tasks"), list):
        return ["board must be a mapping with a `tasks` list"]
    owners = data.get("owners") or {}
    seen: set[str] = set()
    ids = {t.get("id") for t in data["tasks"] if isinstance(t, dict)}
    for i, t in enumerate(data["tasks"]):
        if not isinstance(t, dict):
            errs.append(f"task #{i}: not a mapping")
            continue
        tid = t.get("id", f"#{i}")
        for k in REQUIRED:
            if k not in t:
                errs.append(f"{tid}: missing `{k}`")
        if tid in seen:
            errs.append(f"{tid}: duplicate id")
        seen.add(tid)
        if t.get("state") not in STATES:
            errs.append(f"{tid}: bad state {t.get('state')!r}")
        if owners and t.get("owner") not in owners:
            errs.append(f"{tid}: unknown owner {t.get('owner')!r}")
        bl = t.get("blockers", [])
        if not isinstance(bl, list):
            errs.append(f"{tid}: blockers must be a list")
            continue
        for b in bl:
            if ID_RE.match(str(b)) and b not in ids:
                errs.append(f"{tid}: blocker {b} is not a task")
            if b == tid:
                errs.append(f"{tid}: blocks itself")
    return errs


def parse(text: str) -> Board:
    data = yaml.safe_load(text)
    errs = validate(data)
    if errs:
        raise BoardError("invalid board:\n  " + "\n  ".join(errs))
    return data


def default_file() -> Path:
    return REPO / REL


def load(file: Path | None = None, ref: str | None = None) -> Board:
    if ref:
        out = subprocess.run(
            ["git", "-C", str(REPO), "show", f"{ref}:{REL}"],
            capture_output=True, text=True, check=False,
        )
        if out.returncode != 0:
            raise BoardError(f"{REL} not found on {ref}")
        return parse(out.stdout)
    path = file or default_file()
    if not path.exists():
        raise BoardError(f"no board at {path}")
    return parse(path.read_text(encoding="utf-8"))


def save(data: Board, file: Path | None = None) -> Path:
    errs = validate(data)
    if errs:
        raise BoardError("refusing to save invalid board:\n  " + "\n  ".join(errs))
    path = file or default_file()
    body = yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=200)
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=".board.", suffix=".yaml")
    with os.fdopen(fd, "w", encoding="utf-8") as fh:
        fh.write(HEADER + body)
    os.replace(tmp, path)
    return path


# ---------------------------------------------------------------- queries

def owner_branches(owner: dict[str, Any]) -> list[str]:
    """An owner lists `branches:` (or a single legacy `branch:`)."""
    brs = owner.get("branches")
    if brs is None:
        brs = [owner["branch"]] if owner.get("branch") else []
    return list(brs)


def by_id(data: Board) -> dict[str, Task]:
    return {t["id"]: t for t in data["tasks"]}


def blocker_ok(b: str, task: Task, idx: dict[str, Task], exclude: set[str]) -> bool:
    if not ID_RE.match(str(b)) or b not in idx:
        return False  # external blocker
    dep = idx[b]
    if dep["state"] == "done":
        return True
    same_owner = dep["owner"] == task["owner"]
    return same_owner and (dep["state"] == "review" or b in exclude)


def open_blockers(task: Task, idx: dict[str, Task], exclude: set[str]) -> list[str]:
    return [b for b in task.get("blockers") or [] if not blocker_ok(b, task, idx, exclude)]


def next_task(
    data: Board, owner: str, exclude: set[str] | None = None
) -> tuple[Task | None, str]:
    """Return (task, reason). task is None when nothing is pickable."""
    exclude = exclude or set()
    idx = by_id(data)
    mine = [t for t in data["tasks"] if t["owner"] == owner and t["id"] not in exclude]
    for t in mine:
        if t["state"] == "doing":
            return t, "resume"
    waiting = []
    for t in mine:
        if t["state"] != "todo":
            continue
        ob = open_blockers(t, idx, exclude)
        if not ob:
            return t, "next"
        waiting.append(f"{t['id']} waits on {', '.join(ob)}")
    return None, "; ".join(waiting) if waiting else f"no todo rows for {owner}"


def move(data: Board, tid: str, state: str, sha: str | None = None, now: str | None = None) -> Task:
    if state not in STATES:
        raise BoardError(f"bad state {state!r}; one of {', '.join(STATES)}")
    idx = by_id(data)
    if tid not in idx:
        raise BoardError(f"no task {tid}")
    t = idx[tid]
    t["state"] = state
    if sha:
        t["sha"] = sha
    stamp = now or dt.datetime.now(dt.UTC).strftime("%Y-%m-%dT%H:%M:%SZ")
    t.setdefault("times", {})
    if not isinstance(t["times"], dict):
        t["times"] = {}
    t["times"][state] = stamp
    return t


# ---------------------------------------------------------------- output

def line(t: Task, idx: dict[str, Task] | None = None) -> str:
    bl = ", ".join(t.get("blockers") or []) or "—"
    return (f"{t['id']:<7} {t['state']:<7} {t['owner']:<4} {t['branch']:<15} {t['title']}"
            f"  | done when: {t['done_when']}  | blockers: {bl}")


def tsv(t: Task) -> str:
    fields = [t["id"], t["state"], t["owner"], t["branch"], t.get("sha") or "",
              (t.get("times") or {}).get("done", ""), t["title"]]
    return "\t".join(str(f) for f in fields)


def _cell(s: Any) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ")


def render(data: Board) -> str:
    owners = data.get("owners") or {}
    legend = " · ".join(f"`{k}` {v.get('session', '')} ({', '.join(owner_branches(v))})"
                        for k, v in owners.items())
    out = [
        "# Task board: Astronaut Health Monitor demo",
        "",
        "<!-- GENERATED by `tools/ops/board.py render` from docs/ops/board.yaml. Do not edit. -->",
        "",
        "Source of truth: `docs/ops/board.yaml` (single writer: the coordinator).",
        "Next task for a worker: `tools/ops/board.py list --owner <id> --next`.",
        "\"Done when\" always includes `pytest && ruff check .` passing on the branch.",
        "",
        f"Owners: {legend}",
    ]
    for state in RENDER_ORDER:
        rows = [t for t in data["tasks"] if t["state"] == state]
        out += ["", f"## {state} ({len(rows)})", "",
                "| ID | Task | Owner | Branch | Done when | Blockers | sha |",
                "|----|------|-------|--------|-----------|----------|-----|"]
        for t in rows:
            bl = ", ".join(t.get("blockers") or []) or "—"
            out.append("| " + " | ".join(_cell(x) for x in (
                t["id"], t["title"], t["owner"], t["branch"].removeprefix("feat/"),
                t["done_when"], bl, t.get("sha") or "")) + " |")
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------- CLI

def _load_for_list(args: argparse.Namespace) -> Board:
    if args.file:
        return load(file=Path(args.file))
    ref = args.ref or os.environ.get("BASE_BRANCH", "main")
    try:
        return load(ref=ref)
    except BoardError:
        if args.ref:
            raise
        _out(f"note: no board on {ref} yet; using working tree", file=sys.stderr)
        return load()


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(prog="board.py", description=__doc__.split("\n")[0])
    p.add_argument("--file", help="board yaml path (default: <repo>/docs/ops/board.yaml)")
    sub = p.add_subparsers(dest="cmd", required=True)

    pl = sub.add_parser("list")
    pl.add_argument("--ref", help="read the board from this git ref (default main)")
    pl.add_argument("--owner")
    pl.add_argument("--state", choices=STATES)
    pl.add_argument("--next", action="store_true")
    pl.add_argument("--exclude", nargs="*", default=[], metavar="ID")
    pl.add_argument("--format", choices=("text", "tsv"), default="text")

    pm = sub.add_parser("move")
    pm.add_argument("id")
    pm.add_argument("state", choices=STATES)
    pm.add_argument("--sha")

    pr = sub.add_parser("render")
    pr.add_argument("--out")

    sub.add_parser("validate")
    sub.add_parser("owners", help="tsv: id, session, branch")
    args = p.parse_args(argv)

    try:
        if args.cmd == "list":
            data = _load_for_list(args)
            fmt = tsv if args.format == "tsv" else line
            if args.next:
                if not args.owner:
                    p.error("--next needs --owner")
                t, why = next_task(data, args.owner, set(args.exclude))
                if t is None:
                    _out(f"none: {why}")
                    return 3
                _out(f"{why}: {fmt(t)}")
                return 0
            for t in data["tasks"]:
                if args.owner and t["owner"] != args.owner:
                    continue
                if args.state and t["state"] != args.state:
                    continue
                _out(fmt(t))
            return 0

        file = Path(args.file) if args.file else None
        data = load(file=file)
        if args.cmd == "owners":
            for k, v in (data.get("owners") or {}).items():
                for br in owner_branches(v):
                    _out(f"{k}\t{v.get('session', '')}\t{br}")
            return 0
        if args.cmd == "validate":
            _out(f"ok: {len(data['tasks'])} tasks")
            return 0
        if args.cmd == "move":
            t = move(data, args.id, args.state, args.sha)
            save(data, file)
            _out(line(t))
            return 0
        if args.cmd == "render":
            src = file or default_file()
            out = Path(args.out) if args.out else src.with_name("BOARD.md")
            out.write_text(render(data), encoding="utf-8")
            _out(f"wrote {out.name}")
            return 0
    except BoardError as e:
        _out(f"error: {e}", file=sys.stderr)
        return 1
    return 1


if __name__ == "__main__":
    sys.exit(main())
